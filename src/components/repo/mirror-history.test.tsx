import { createHash } from 'node:crypto';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { renderToStaticMarkup } from 'react-dom/server';
import type { CommitPage, RepositoryCommit } from '../../../shared/history';
import { provenanceOf } from '../../../shared/provenance';
import { api, resetWorkspaceCaches } from '../../lib/api';
import { textOf } from '../../test/fixtures';

vi.mock('../../lib/resources', () => ({ useRead: vi.fn() }));
vi.mock('../../store/workspace', () => ({ useSnapshot: vi.fn() }));
vi.mock('../../lib/hooks', () => ({ useNow: () => Date.parse('2026-10-14T10:00:12Z') }));
import { aggregateHistory, mirrorHistory } from './mirror-history';
import { ImportBar } from './ImportBar';

const hash = (value: string) => createHash('sha1').update(value).digest('hex');
const entry = (kind: RepositoryCommit['author']['kind'], name: string, index = 0): RepositoryCommit => ({
  hash: hash(`${kind}:${name}:${index}`), title: 'Preserve the remote cwd filter in the resume picker', at: '2026-10-14T10:00:00Z', author: { kind, id: `${kind}:${name}`, name },
});
const page = (count: number, nextCursor: string | null): CommitPage => ({ ref: hash('default-branch'), path: '', items: Array.from({ length: count }, (_, i) => entry('agent', 'Codex', i)), nextCursor });
afterEach(() => { vi.restoreAllMocks(); resetWorkspaceCaches(); });

describe('mirror authorship', () => {
  it('counts only explicit agents, keeps bots separate and combines human/GitHub people', () => {
    const summary = aggregateHistory([entry('agent', 'Codex'), entry('bot', 'dependabot[bot]'), entry('human', 'Claude'), entry('github', 'Alex Morgan'), entry('simulated', 'Fixture agent')]);
    expect(summary.agentCommits).toBe(1);
    expect(summary.people.commits).toBe(2);
    expect(summary.agents.find(row => row.kind === 'bot')).toMatchObject({ name: 'dependabot[bot]', commits: 1 });
    expect(summary.agents.find(row => row.kind === 'simulated')).toMatchObject({ name: 'Simulated', commits: 1 });
  });
  it('never infers an agent from a person name or commit subject', () => {
    const commit = entry('human', 'Codex'); commit.title = 'Generated by Claude Code';
    expect(aggregateHistory([commit]).agentCommits).toBe(0);
  });
  it('aggregates an attributed agent trailer without including its email', () => {
    const commit = entry('human', 'Alex Morgan');
    const facts = provenanceOf({ id: commit.hash, at: commit.at, author: { name: 'Alex Morgan', email: 'alex@example.test' }, message: `${commit.title}\n\nCo-authored-by: Claude Opus 5.5 <noreply@anthropic.com>` });
    commit.author = { kind: facts.kind, id: commit.hash, name: facts.agent!.name, model: facts.agent?.model, tool: facts.agent?.tool };
    const summary = aggregateHistory([commit]);
    expect(summary.agentCommits).toBe(1);
    expect(summary.agents[0].name).toBe('Claude Opus 5.5');
    expect(JSON.stringify(summary)).not.toContain('@');
  });
  it('groups models by tool, ignores tool versions, deduplicates commits and keeps history order', () => {
    const first = entry('agent', 'GPT-6 Astra', 1); first.author.model = 'gpt-6-astra'; first.author.tool = 'codex/1.8.0';
    const second = entry('agent', 'GPT-6 Astra', 2); second.author.model = first.author.model; second.author.tool = 'codex/1.9.0'; second.at = '2026-10-15T00:00:00Z';
    const third = entry('agent', 'GPT-6 Astra', 3); third.author.model = first.author.model; third.author.tool = 'cursor';
    const summary = aggregateHistory([first, second, first, third]);
    expect(summary.total).toBe(3);
    expect(summary.agents.map(row => [row.name, row.tool, row.commits])).toEqual([['GPT-6 Astra', 'Codex', 2], ['GPT-6 Astra', 'Cursor', 1]]);
    expect(summary.agents[0].latest?.hash).toBe(first.hash);
  });
  it('uses the actual sample size and caps expanded results at 300', () => {
    expect(aggregateHistory(page(312, null).items).total).toBe(100);
    expect(aggregateHistory(page(312, null).items, 300).total).toBe(300);
    expect(aggregateHistory(page(12, null).items).total).toBe(12);
  });
  it('reads the 100 newest commits once per tip for the commit row on Code', async () => {
    const first = page(100, 'next');
    const read = vi.spyOn(api, 'commits').mockResolvedValue(first);
    await Promise.all([mirrorHistory.load(first.ref, false), mirrorHistory.load(first.ref, false)]);
    await mirrorHistory.load(first.ref, false);
    expect(read).toHaveBeenCalledTimes(1);
    expect(read).toHaveBeenCalledWith(first.ref, '', null, 100);
  });
  it('re-reads completed ancestry at the same tip and forgets another workspace’s data', async () => {
    const first = page(1, null);
    const read = vi.spyOn(api, 'commits').mockResolvedValue(first);
    await mirrorHistory.load(first.ref, true);
    await mirrorHistory.load(first.ref, false);
    resetWorkspaceCaches();
    await mirrorHistory.load(first.ref, false);
    expect(read).toHaveBeenCalledTimes(3);
  });
});

describe('mirror import elapsed time', () => {
  it('keeps the import to one line, without moving progress or source text', () => {
    const html = renderToStaticMarkup(<ImportBar importing={{ source: 'https://github.com/openai/codex', name: 'codex', branch: 'main', startedAt: '2026-10-14T10:00:00Z' }} />);
    expect(textOf(html).trim()).toBe('Copying from GitHub 12s');
    expect(html).not.toMatch(/progress|spinner|Loading|github.com/);
  });
});
