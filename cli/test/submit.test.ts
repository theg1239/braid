import { mkdirSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { parseNote } from '../../shared/provenance';
import { saveCredentials, writeLink } from '../src/config';
import { braid, cleanup, json, repository, server, session, type Sent } from './helpers';

afterEach(cleanup);

const origin = 'https://braid.example';
const agentEnv = { BRAID_MODEL: 'claude-opus-5-5', BRAID_TOOL: 'claude-code/2.1.291', BRAID_SESSION: 's_run', BRAID_PARENT_SESSION: 's_orchestrator' };
const change = (revision: number, extra: Record<string, unknown> = {}) => ({ id: 'ch_0123456789abc', number: 7, title: 'Add the parser', status: 'open', revision, conflicts: [], checks: [], reviews: [], overlaps: [], events: [], ...extra });

/** A signed-in, linked repository whose trunk is its first commit, with an agent's commit on a branch. */
function workspace() {
  const repo = repository();
  const base = repo.commit({ 'parser.ts': 'export const parse = () => null;\n' }, 'Start');
  repo.git(['checkout', '-q', '-b', 'parser']);
  repo.commit({ 'parser.ts': 'export const parse = (text: string) => text.trim();\n', 'notes.md': 'Parser notes\n' }, 'Add the parser\n\nTrim input before parsing.\n\nCo-authored-by: Claude Opus 5.5 <noreply@anthropic.com>');
  saveCredentials(repo.env, { origin, accessToken: `braid_agent_${'c'.repeat(64)}`, workspaceId: 'ws_1', expiresAt: new Date(Date.now() + 86_400_000).toISOString() });
  writeLink(repo.root, { url: origin, workspaceId: 'ws_1' });
  writeFileSync(join(repo.root, '.git', 'info', 'exclude'), '');
  return { ...repo, base, env: { ...repo.env, ...agentEnv } };
}
const routes = (base: string, extra = {}) => ({
  'POST /api/agent/session': session(),
  'POST /api/changes/checkout': () => json({ remote: 'https://git.example/repo.git', token: 'read-token-value', branch: 'main', head: base, expiresAt: new Date().toISOString() }),
  ...extra,
});
const submitted = (sent: Sent[], path: string) => sent.filter(request => request.method === 'POST' && request.path === path);

describe('braid submit', () => {
  it('keeps the committed agent run after the tool exits and its environment is gone', async () => {
    const repo = workspace();
    repo.git(['notes', '--ref=braid', 'add', '-m', JSON.stringify({ v: 1, agent: { name: 'GPT-6.1 Sol', model: 'gpt-6.1-sol', tool: 'codex/1.8.0', session: 's_committed', parentSession: 's_parent' } }), 'HEAD']);
    const env = Object.fromEntries(Object.entries(repo.env).filter(([key]) => !Object.hasOwn(agentEnv, key)));
    const api = server(routes(repo.base, { 'POST /api/changes': () => json(change(1), 201) }));
    expect((await braid(['submit'], { cwd: repo.root, env, fetch: api.fetch })).exitCode).toBe(0);
    expect(submitted(api.sent, '/api/changes')[0].body).toMatchObject({ model: 'gpt-6.1-sol', agent: { tool: 'codex/1.8.0', session: 's_committed', parentSession: 's_parent' } });
  });

  it('drops a coding tool\'s footer from the summary but keeps a paragraph that only mentions generated code', async () => {
    const repo = workspace();
    repo.git(['commit', '-q', '--amend', '-m', 'Add the parser\n\nTrim input before parsing.\n\nThe tables are generated by protoc.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-authored-by: Claude Opus 5.5 <noreply@anthropic.com>']);
    const api = server(routes(repo.base, { 'POST /api/changes': () => json(change(1), 201) }));
    expect((await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: api.fetch })).exitCode).toBe(0);
    expect(submitted(api.sent, '/api/changes')[0].body).toMatchObject({ summary: 'Trim input before parsing.\n\nThe tables are generated by protoc.' });
  });

  it('never assigns this run to an older Claude model just because they share an address', async () => {
    const repo = workspace();
    repo.commit({ 'old.ts': 'export const old = 1;\n' }, 'Earlier run\n\nCo-authored-by: Claude Opus 4.7 <noreply@anthropic.com>');
    const api = server(routes(repo.base, { 'POST /api/changes': () => json(change(1), 201) }));
    expect((await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: api.fetch })).exitCode).toBe(0);
    expect(repo.git(['notes', '--ref=braid', 'list'])).not.toContain(repo.git(['rev-parse', 'HEAD']));
  });

  it('opens a change from the commits since trunk with the agent run, then revises it', async () => {
    const repo = workspace();
    const braidServer = server(routes(repo.base, { 'POST /api/changes': () => json(change(1), 201), 'GET /api/changes/ch_0123456789abc': () => json(change(1)), 'POST /api/changes/ch_0123456789abc/revisions': () => json(change(2)) }));
    const first = await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(first.stderr).toBe('');
    expect(first.stdout).toBe('Pull request #7 · Add the parser · open · revision 1\nNext, wait until it merges or needs changes:\n  braid wait\n');
    const [opened] = submitted(braidServer.sent, '/api/changes');
    expect(opened.headers['idempotency-key']).toMatch(/^[a-zA-Z0-9_-]{16,128}$/);
    expect(opened.headers.authorization).toMatch(/^Bearer braid_at_/);
    expect(opened.headers['x-braid-workspace']).toBe('ws_1');
    expect(opened.body).toEqual({
      title: 'Add the parser', summary: 'Trim input before parsing.', model: 'claude-opus-5-5',
      agent: { tool: 'claude-code/2.1.291', session: 's_run', parentSession: 's_orchestrator' },
      coAuthors: ['Claude Opus 5.5 <noreply@anthropic.com>'],
      baseCommit: repo.base,
      files: [{ path: 'notes.md', content: 'Parser notes\n' }, { path: 'parser.ts', content: 'export const parse = (text: string) => text.trim();\n' }],
    });
    // The post-commit hook was not installed, so submit records the run on the commit that credits the model.
    expect(parseNote(repo.git(['notes', '--ref=refs/notes/braid', 'show', 'HEAD']))).toMatchObject({ v: 1, agent: { name: 'Claude Opus 5.5', model: 'claude-opus-5-5', session: 's_run' } });

    repo.commit({ 'parser.ts': 'export const parse = (text: string) => text.trim().toLowerCase();\n' }, 'Lowercase too');
    const second = await braid(['submit', '--summary', 'Trim and lowercase input.'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(second.stdout).toContain('Pull request #7 · Add the parser · open · revision 2');
    const [revised] = submitted(braidServer.sent, '/api/changes/ch_0123456789abc/revisions');
    expect(revised.body).toMatchObject({ title: 'Add the parser', summary: 'Trim and lowercase input.', previousRevision: 1, baseCommit: repo.base });
    expect(revised.headers['idempotency-key']).not.toBe(opened.headers['idempotency-key']);
  });

  it('sends the co-author lines the commits carry, as written, once each and at most five', async () => {
    const repo = workspace();
    const lines = ['Alice <alice@example.com>', 'GPT-6.1 Sol <gpt-6.1-sol@agents.braid.local>', 'Bob <bob@example.com>', 'Carol <carol@example.com>', 'Dan <dan@example.com>', 'Erin <erin@example.com>'];
    repo.commit({ 'a.txt': '1\n' }, `One\n\nCo-authored-by: ${lines[0]}\nCo-authored-by: <nameless@example.com>\nCo-authored-by: ${'L'.repeat(190)} <long@example.com>`);
    repo.commit({ 'a.txt': '2\n' }, `Two\n\nCo-authored-by: ${lines[1]}\nCo-Authored-By: ${lines[0]}\nCo-authored-by: Claude Opus 5.5 <noreply@anthropic.com>`);
    repo.commit({ 'a.txt': '3\n' }, `Three\n\n${lines.slice(2).map(line => `Co-authored-by: ${line}`).join('\n')}`);
    repo.commit({ 'a.txt': '4\n' }, 'Four, with no co-author');
    const braidServer = server(routes(repo.base, { 'POST /api/changes': () => json(change(1), 201) }));
    expect((await braid(['submit', '--title', 'Many hands'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch })).exitCode).toBe(0);
    expect((submitted(braidServer.sent, '/api/changes')[0].body as { coAuthors: string[] }).coAuthors).toEqual(['Claude Opus 5.5 <noreply@anthropic.com>', lines[0], lines[1], lines[2], lines[3]]);
  });

  it('opens a new change once the last one landed or closed', async () => {
    const repo = workspace();
    const braidServer = server(routes(repo.base, {
      'POST /api/changes': [() => json(change(1), 201), () => json({ ...change(1), id: 'ch_00000000000b2', number: 8 }, 201)],
      'GET /api/changes/ch_0123456789abc': () => json(change(1, { status: 'closed', closeReason: 'superseded' })),
    }));
    await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    repo.commit({ 'parser.ts': 'export const parse = (text: string) => text;\n' }, 'Start over');
    const again = await braid(['submit', '--title', 'Parse plainly'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(again.stdout).toContain('Pull request #8 · Add the parser · open · revision 1');
    const created = submitted(braidServer.sent, '/api/changes');
    expect(created).toHaveLength(2);
    expect(created[1].body).toMatchObject({ title: 'Parse plainly', baseCommit: repo.base });
    expect(created[1].body).not.toHaveProperty('previousRevision');
  });

  it('refuses credentials, uncommitted work and protected paths before anything is sent', async () => {
    const repo = workspace();
    const braidServer = server(routes(repo.base, { 'POST /api/changes': () => json(change(1), 201) }));
    writeFileSync(join(repo.root, 'draft.ts'), 'unfinished\n');
    const dirty = await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(dirty.stderr).toContain('Commit your work before submitting; the change is read from commits. Not committed: draft.ts.');
    repo.commit({ 'draft.ts': `const token = "ghp_${'A1b2'.repeat(9)}";\n` }, 'Add a token');
    const secret = await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(secret.exitCode).toBe(1);
    expect(secret.stderr).toContain('draft.ts looks like it contains a credential');
    expect(secret.stderr).not.toContain('ghp_');
    repo.git(['reset', '-q', '--hard', 'HEAD~1']);
    expect((await braid(['submit', '--summary', `Uses ghp_${'A1b2'.repeat(9)}`], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch })).stderr).toContain('Possible secret detected.');
    writeFileSync(join(repo.home, 'tests.json'), `[${' '.repeat(128_000)}]`);
    symlinkSync(join(repo.home, 'tests.json'), join(repo.home, 'linked.json'));
    expect((await braid(['submit', '--tests', join(repo.home, 'tests.json')], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch })).stderr).toContain('The tests file must be a regular file of at most 128 KB.');
    expect((await braid(['submit', '--tests', join(repo.home, 'linked.json')], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch })).stderr).toContain('Cannot read the tests file');
    repo.commit({ '.env': 'NAME=value\n' }, 'Add env');
    expect((await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch })).stderr).toContain('.env is a protected or invalid path');
    expect(submitted(braidServer.sent, '/api/changes')).toHaveLength(0);
  });

  it('keeps an unconfirmed submission and resends it exactly with --retry', async () => {
    const repo = workspace();
    const braidServer = server(routes(repo.base, { 'POST /api/changes': [() => json({ error: 'The operation could not complete.' }, 503), () => json(change(1), 201)] }));
    const failed = await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(failed.exitCode).toBe(1);
    expect(failed.stderr).toContain('The submission is unconfirmed; resend it exactly with braid submit --retry.');
    const blocked = await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(blocked.stderr).toContain('An earlier submission from this branch is unconfirmed.');
    const retried = await braid(['submit', '--retry'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(retried.exitCode).toBe(0);
    const [original, resent] = submitted(braidServer.sent, '/api/changes');
    expect(resent.headers['idempotency-key']).toBe(original.headers['idempotency-key']);
    expect(resent.body).toEqual(original.body);
  });

  it('reports a refusal with Braid\'s reason and lets the next submission through', async () => {
    const repo = workspace();
    const braidServer = server(routes(repo.base, { 'POST /api/changes': [() => json({ error: 'Name the tool with at most 80 letters.' }, 400), () => json(change(1), 201)] }));
    const refused = await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(refused.stderr).toContain('Braid did not accept the change (HTTP 400): Name the tool with at most 80 letters.');
    expect((await braid(['submit'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch })).exitCode).toBe(0);
  });

  it('runs .braid/proof.json and attaches each check, failing or not, but never one that prints a credential', async () => {
    const repo = workspace();
    mkdirSync(join(repo.root, '.braid'), { recursive: true });
    const proof = (checks: string[]) => writeFileSync(join(repo.root, '.braid', 'proof.json'), JSON.stringify({ checks }));
    proof(['echo proof-ok', 'printf "\\033[31mbroken\\033[0m\\n" >&2; exit 3', 'printenv BRAID_MODEL || echo no-braid-variables', 'printf "10%%\\r100%%\\n"']);
    const braidServer = server(routes(repo.base, { 'POST /api/changes': () => json(change(1), 201), 'GET /api/changes/ch_0123456789abc': () => json(change(1)) }));
    const result = await braid(['submit', '--proof'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(result.exitCode).toBe(0);
    expect(result.stderr).toContain('Proof: echo proof-ok exited 0');
    const evidence = (submitted(braidServer.sent, '/api/changes')[0].body as { evidence: unknown[] }).evidence;
    expect(evidence).toEqual([
      { kind: 'command', command: 'echo proof-ok', exitCode: 0, output: 'proof-ok\n', durationMs: expect.any(Number) },
      { kind: 'command', command: 'printf "\\033[31mbroken\\033[0m\\n" >&2; exit 3', exitCode: 3, output: 'broken\n', durationMs: expect.any(Number) },
      { kind: 'command', command: 'printenv BRAID_MODEL || echo no-braid-variables', exitCode: 0, output: 'no-braid-variables\n', durationMs: expect.any(Number) },
      { kind: 'command', command: 'printf "10%%\\r100%%\\n"', exitCode: 0, output: '100%\n', durationMs: expect.any(Number) },
    ]);

    repo.commit({ 'parser.ts': 'export const parse = (text: string) => text;\n' }, 'Again');
    proof([`echo "token ghp_${'A1b2'.repeat(9)}"`]);
    expect((await braid(['submit', '--proof'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch })).stderr).toContain('.braid/proof.json looks like it contains a credential.');
    proof([`echo "token ghp_$(printf 'A1b2%.0s' 1 2 3 4 5 6 7 8 9)"`]);
    const leaked = await braid(['submit', '--proof'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch });
    expect(leaked.stderr).toContain('looks like it contains a credential, so nothing was submitted');
    expect(leaked.stderr).not.toContain('A1b2A1b2');
    writeFileSync(join(repo.root, '.braid', 'proof.json'), '{"checks": ["npm test"], "deploy": true}');
    expect((await braid(['submit', '--proof'], { cwd: repo.root, env: repo.env, fetch: braidServer.fetch })).stderr).toContain('.braid/proof.json is an object with checks, timeoutSeconds and preview.');
    expect(submitted(braidServer.sent, '/api/changes')).toHaveLength(1);
  });
});
